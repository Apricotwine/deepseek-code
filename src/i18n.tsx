const dicts: Record<Language, typeof zh> = { zh, en };

type Params = Record<string, string | number>;

function resolve(obj: unknown, path: string): unknown {
  let cur: unknown = obj;
  for (const part of path.split(".")) {
    if (cur && typeof cur === "object" && part in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[part];
    } else {
      return undefined;
    }
  }
  return cur;
}

export function makeT(language: Language) {
  const dict = dicts[language] ?? dicts.en;
  return (key: string, params?: Params): string => {
    const raw = resolve(dict, key) ?? resolve(dicts.en, key) ?? key;
    let out = String(raw);
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        out = out.replaceAll(`{${k}}`, String(v));
      }
    }
    return out;
  };
}

export type TFunc = ReturnType<typeof makeT>;

interface I18nValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: TFunc;
}

const I18nContext = createContext<I18nValue>({
  language: "zh",
  setLanguage: () => {},
  t: makeT("zh"),
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>("zh");
  const t = useMemo(() => makeT(language), [language]);
  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
